function buildModuleMetricTrend(input: {
  key: string;
  label: string;
  sessions: WeeklyTrainingRecordSummary[];
  trainingTypes: WeeklyTrainingReportTrainingType[];
  metricSelector: (session: WeeklyTrainingRecordSummary) => number | undefined;
  higherIsBetter: boolean;
  threshold: number;
  formatter: (value: number) => string;
  plainMetricName: string;
}): WeeklyMetricTrend {
  const values = input.sessions
    .filter((session) => input.trainingTypes.includes(session.trainingType))
    .map(input.metricSelector)
    .filter((value): value is number => value !== undefined);

  return calculateTrend({
    key: input.key,
    label: input.label,
    values,
    higherIsBetter: input.higherIsBetter,
    threshold: input.threshold,
    formatter: input.formatter,
    plainMetricName: input.plainMetricName
  });
}

function buildEegMetricTrend(input: {
  key: string;
  label: string;
  sessions: WeeklyTrainingRecordSummary[];
  metricSelector: (session: WeeklyTrainingRecordSummary) => number | undefined;
  higherIsBetter: boolean;
  threshold: number;
  plainMetricName: string;
}): WeeklyMetricTrend {
  const values = input.sessions
    .map(input.metricSelector)
    .filter((value): value is number => value !== undefined);

  return calculateTrend({
    key: input.key,
    label: input.label,
    values,
    higherIsBetter: input.higherIsBetter,
    threshold: input.threshold,
    formatter: (value) => `${formatNumber(value)}/100`,
    plainMetricName: input.plainMetricName
  });
}

function calculateTrend(input: {
  key: string;
  label: string;
  values: number[];
  higherIsBetter: boolean;
  threshold: number;
  formatter: (value: number) => string;
  plainMetricName: string;
}): WeeklyMetricTrend {
  if (input.values.length < 2) {
    return {
      key: input.key,
      label: input.label,
      direction: "not_enough_data",
      sampleCount: input.values.length,
      displayValue:
        input.values.length === 1 ? input.formatter(input.values[0] ?? 0) : "暂无足够数据",
      summary: `${input.plainMetricName}样本不足，暂不做趋势判断。`
    };
  }

  const splitIndex = Math.max(1, Math.floor(input.values.length / 2));
  const firstHalfAverage = average(input.values.slice(0, splitIndex));
  const secondHalfAverage = average(input.values.slice(splitIndex));
  const rawDelta = secondHalfAverage - firstHalfAverage;
  const effectiveDelta = input.higherIsBetter ? rawDelta : -rawDelta;
  const direction =
    Math.abs(rawDelta) < input.threshold
      ? "stable"
      : effectiveDelta > 0
        ? "improving"
        : "needs_attention";

  return {
    key: input.key,
    label: input.label,
    direction,
    sampleCount: input.values.length,
    firstHalfAverage,
    secondHalfAverage,
    displayValue: `${input.formatter(firstHalfAverage)} -> ${input.formatter(secondHalfAverage)}`,
    summary: buildTrendSummary({
      metricName: input.plainMetricName,
      direction,
      firstHalfAverage,
      secondHalfAverage,
      formatter: input.formatter,
      higherIsBetter: input.higherIsBetter
    })
  };
}

function buildTrendSummary(input: {
  metricName: string;
  direction: WeeklyTrendDirection;
  firstHalfAverage: number;
  secondHalfAverage: number;
  formatter: (value: number) => string;
  higherIsBetter: boolean;
}): string {
  const changeText = `${input.metricName}从 ${input.formatter(
    input.firstHalfAverage
  )} 到 ${input.formatter(input.secondHalfAverage)}`;

  if (input.direction === "improving") {
    return `${changeText}，本周后半段呈现更稳定的训练趋势。`;
  }
  if (input.direction === "stable") {
    return `${changeText}，整体保持稳定。`;
  }
  if (input.higherIsBetter) {
    return `${changeText}，建议下周保持基础难度并观察变化。`;
  }
  return `${changeText}，建议下周降低任务复杂度并关注训练节奏。`;
}

function buildSignalQualitySummary(sessions: WeeklyTrainingRecordSummary[]): string {
  const qualities = sessions
    .map((session) => session.eegSummaryMetrics?.qualityStatus)
    .filter((quality): quality is WeeklyTrainingEegQualityStatus => quality !== undefined);
  if (qualities.length === 0) {
    return "本周未记录足够 EEG 信号质量数据。";
  }

  const unstableCount = qualities.filter((quality) => quality !== "good").length;
  const unstableRate = unstableCount / qualities.length;
  if (unstableRate === 0) {
    return "本周 EEG 信号质量整体稳定，可作为趋势参考。";
  }
  if (unstableRate < 0.35) {
    return "本周少量训练出现信号波动，查看趋势时建议结合佩戴状态。";
  }
  return "本周 EEG 信号波动较多，建议下周先检查佩戴和连接状态。";
}

function buildNextWeekSuggestions(input: {
  completionRate: number;
  trends: WeeklyTrainingTrendSet;
}): string[] {
  const suggestions: string[] = [];

  if (input.completionRate < 0.7) {
    suggestions.push("下周先保持较短、可暂停的训练安排，优先提高任务完成稳定性。");
  }
  if (input.trends.attentionTraining.direction === "needs_attention") {
    suggestions.push("注意力训练建议维持基础难度，减少一次性出现的干扰项数量。");
  }
  if (input.trends.reaction.direction === "needs_attention") {
    suggestions.push("点击反应任务建议适当延长刺激间隔，先观察反应时波动是否收敛。");
  }
  if (input.trends.impulseControl.direction === "needs_attention") {
    suggestions.push("Go/No-Go 训练建议保留低到中等难度，规则变化前给出更清晰提示。");
  }
  if (input.trends.rhythmNavigation.direction === "needs_attention") {
    suggestions.push("节律导航建议先使用短路线和慢节拍，再逐步增加任务切换规则。");
  }
  if (input.trends.musicAdaptation.direction === "needs_attention") {
    suggestions.push("音乐素材建议优先选择用户反馈更舒适、强度较低的曲目。");
  }
  if (input.trends.eeg.fatigue.direction === "needs_attention") {
    suggestions.push("疲劳趋势升高时，建议缩短单次时长，并在训练后加入休息或低强度音乐。");
  }
  if (input.trends.eeg.attention.direction === "improving" && input.completionRate >= 0.8) {
    suggestions.push("若下周完成率继续稳定，可在治疗师确认后小幅增加任务复杂度。");
  }

  return suggestions.length > 0
    ? suggestions
    : ["下周建议维持当前训练频率和强度，继续记录完成率、反应时和 EEG 数据质量。"];
}

