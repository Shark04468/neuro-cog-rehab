function buildPdfLines(view: WeeklyTrainingReportView): string[] {
  const lines = [view.title, view.scopeNotice, ""];

  lines.push("本周概览");
  for (const card of view.summaryCards) {
    lines.push(`${card.label}: ${card.value}`);
  }
  lines.push("");

  lines.push("训练趋势");
  for (const card of view.trendCards) {
    lines.push(`${card.label}: ${card.status}`);
    lines.push(card.description);
  }
  lines.push("");

  for (const section of view.sections) {
    lines.push(section.title);
    for (const row of section.rows) {
      lines.push(`${row.label}: ${row.value}`);
    }
    lines.push("");
  }

  lines.push("下周训练建议");
  for (const suggestion of view.nextWeekSuggestions) {
    lines.push(suggestion);
  }

  return lines.flatMap((line) => wrapText(line, 34)).slice(0, 56);
}

function buildSimplePdf(lines: string[]): Uint8Array {
  const content = [
    "BT",
    "/F1 15 Tf",
    "48 790 Td",
    "20 TL",
    ...lines.map((line, index) => `${index === 0 ? "" : "T* "}${encodePdfText(line)} Tj`),
    "ET"
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
    `<< /Length ${asciiByteLength(content)} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type0 /BaseFont /STSong-Light /Encoding /UniGB-UCS2-H /DescendantFonts [6 0 R] >>",
    "<< /Type /Font /Subtype /CIDFontType0 /BaseFont /STSong-Light /CIDSystemInfo << /Registry (Adobe) /Ordering (GB1) /Supplement 2 >> >>"
  ];
  let pdf = "%PDF-1.4\n";
  const offsets = [0];

  objects.forEach((object, index) => {
    offsets.push(asciiByteLength(pdf));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });

  const xrefOffset = asciiByteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (const offset of offsets.slice(1)) {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return new TextEncoder().encode(pdf);
}

function validateWeeklyReportInput(input: WeeklyTrainingReportInput): void {
  requireNonEmpty(input.userInfo.userId, "userInfo.userId is required.");
  requireNonEmpty(input.userInfo.displayName, "userInfo.displayName is required.");
  requireIsoDate(input.period.periodStart, "period.periodStart is invalid.");
  requireIsoDate(input.period.periodEnd, "period.periodEnd is invalid.");
  if (Date.parse(input.period.periodEnd) < Date.parse(input.period.periodStart)) {
    throw new WeeklyTrainingReportGeneratorError(
      "INVALID_INPUT",
      "period.periodEnd cannot be earlier than period.periodStart."
    );
  }
  requireNonNegativeInteger(input.plan.plannedSessionCount, "plan.plannedSessionCount");
  if (input.plan.plannedDurationMinutes !== undefined) {
    requireNonNegative(input.plan.plannedDurationMinutes, "plan.plannedDurationMinutes");
  }

  for (const session of input.sessions) {
    requireNonEmpty(session.sessionId, "session.sessionId is required.");
    requireIsoDate(session.startedAt, "session.startedAt is invalid.");
    if (session.endedAt !== undefined) {
      requireIsoDate(session.endedAt, "session.endedAt is invalid.");
    }
    requireNonNegative(session.durationSeconds, "session.durationSeconds");
    validateBehaviorMetrics(session.behaviorMetrics);
    if (session.eegSummaryMetrics !== undefined) {
      validateEegSummaryMetrics(session.eegSummaryMetrics);
    }
    if (session.musicAdaptation !== undefined) {
      validateMusicAdaptation(session.musicAdaptation);
    }
    if (session.abnormalEventCount !== undefined) {
      requireNonNegativeInteger(session.abnormalEventCount, "session.abnormalEventCount");
    }
  }
}

function validateBehaviorMetrics(metrics: WeeklyBehaviorMetrics): void {
  for (const rateField of [
    "accuracyRate",
    "omissionRate",
    "falseAlarmRate",
    "inhibitorySuccessRate",
    "routeAccuracy"
  ] as const) {
    const value = metrics[rateField];
    if (value !== undefined) {
      requireRate(value, `behaviorMetrics.${rateField}`);
    }
  }
  for (const positiveField of [
    "averageReactionTimeMs",
    "reactionTimeVariabilityMs",
    "timingErrorMs"
  ] as const) {
    const value = metrics[positiveField];
    if (value !== undefined) {
      requireNonNegative(value, `behaviorMetrics.${positiveField}`);
    }
  }
}

function validateEegSummaryMetrics(metrics: WeeklyEegSummaryMetrics): void {
  for (const scoreField of [
    "averageAttentionIndex",
    "averageRelaxationIndex",
    "averageFatigueIndex"
  ] as const) {
    const value = metrics[scoreField];
    if (value !== undefined) {
      requireScore(value, `eegSummaryMetrics.${scoreField}`);
    }
  }
  if (metrics.validSampleRate !== undefined) {
    requireRate(metrics.validSampleRate, "eegSummaryMetrics.validSampleRate");
  }
  if (metrics.artifactCount !== undefined) {
    requireNonNegative(metrics.artifactCount, "eegSummaryMetrics.artifactCount");
  }
  if (metrics.frameCount !== undefined) {
    requireNonNegative(metrics.frameCount, "eegSummaryMetrics.frameCount");
  }
}

function validateMusicAdaptation(metrics: WeeklyMusicAdaptationMetrics): void {
  if (metrics.suitabilityScore !== undefined) {
    requireScore(metrics.suitabilityScore, "musicAdaptation.suitabilityScore");
  }
}

function sanitizeUserInfo(userInfo: WeeklyTrainingReportUserInfo): WeeklyTrainingReportUserInfo {
  const sanitized: WeeklyTrainingReportUserInfo = {
    userId: sanitizePlainText(userInfo.userId),
    displayName: sanitizePlainText(userInfo.displayName)
  };
  if (userInfo.userProfileId !== undefined) {
    sanitized.userProfileId = sanitizePlainText(userInfo.userProfileId);
  }
  if (userInfo.ageRange !== undefined) {
    sanitized.ageRange = sanitizePlainText(userInfo.ageRange);
  }
  if (userInfo.therapistUserId !== undefined) {
    sanitized.therapistUserId = sanitizePlainText(userInfo.therapistUserId);
  }
  if (userInfo.guardianConsentLabel !== undefined) {
    sanitized.guardianConsentLabel = sanitizePlainText(userInfo.guardianConsentLabel);
  }
  return sanitized;
}

function sanitizePeriod(period: WeeklyTrainingReportPeriod): WeeklyTrainingReportPeriod {
  const sanitized: WeeklyTrainingReportPeriod = {
    periodStart: period.periodStart,
    periodEnd: period.periodEnd
  };
  if (period.timezone !== undefined) {
    sanitized.timezone = sanitizePlainText(period.timezone);
  }
  return sanitized;
}

function calculateCompletionRate(
  plannedSessionCount: number,
  completedSessionCount: number
): number {
  if (plannedSessionCount <= 0) {
    return completedSessionCount > 0 ? 1 : 0;
  }
  return clamp(completedSessionCount / plannedSessionCount, 0, 1);
}

function average(values: number[]): number {
  if (values.length === 0) {
    return 0;
  }
  return roundToOneDecimal(values.reduce((sum, value) => sum + value, 0) / values.length);
}

function invertRate(value: number | undefined): number | undefined {
  return value === undefined ? undefined : 1 - value;
}

function sanitizePlainText(value: string): string {
  return FORBIDDEN_REPLACEMENTS.reduce(
    (current, [forbiddenTerm, replacement]) => current.replaceAll(forbiddenTerm, replacement),
    value.trim()
  );
}

function assertNoForbiddenTerms(value: string): void {
  const matched = FORBIDDEN_REPLACEMENTS.map(([term]) => term).find((term) => value.includes(term));
  if (matched) {
    throw new WeeklyTrainingReportGeneratorError(
      "UNSAFE_REPORT_TEXT",
      `Report output contains restricted wording: ${matched}.`
    );
  }
}

function formatRate(value: number): string {
  return `${Math.round(value * 100)}%`;
}

function formatNumber(value: number): string {
  return Number.isInteger(value) ? `${value}` : value.toFixed(1);
}

function roundToOneDecimal(value: number): number {
  return Math.round(value * 10) / 10;
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

function toDateKey(value: string): string {
  return new Date(value).toISOString().slice(0, 10);
}

function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function wrapText(value: string, maxLength: number): string[] {
  if (value.length <= maxLength) {
    return [value];
  }

  const lines: string[] = [];
  for (let start = 0; start < value.length; start += maxLength) {
    lines.push(value.slice(start, start + maxLength));
  }
  return lines;
}

function encodePdfText(value: string): string {
  const hex = ["feff"];
  for (let index = 0; index < value.length; index += 1) {
    hex.push(value.charCodeAt(index).toString(16).padStart(4, "0"));
  }
  return `<${hex.join("")}>`;
}

function asciiByteLength(value: string): number {
  return new TextEncoder().encode(value).length;
}

function requireNonEmpty(value: string, message: string): void {
  if (value.trim().length === 0) {
    throw new WeeklyTrainingReportGeneratorError("INVALID_INPUT", message);
  }
}

function requireIsoDate(value: string, message: string): void {
  if (Number.isNaN(Date.parse(value))) {
    throw new WeeklyTrainingReportGeneratorError("INVALID_INPUT", message);
  }
}

function requireRate(value: number, fieldName: string): void {
  requireFiniteNumber(value, fieldName);
  if (value < 0 || value > 1) {
    throw new WeeklyTrainingReportGeneratorError(
      "INVALID_INPUT",
      `${fieldName} must be between 0 and 1.`
    );
  }
}

function requireScore(value: number, fieldName: string): void {
  requireFiniteNumber(value, fieldName);
  if (value < 0 || value > 100) {
    throw new WeeklyTrainingReportGeneratorError(
      "INVALID_INPUT",
      `${fieldName} must be between 0 and 100.`
    );
  }
}

function requireNonNegative(value: number, fieldName: string): void {
  requireFiniteNumber(value, fieldName);
  if (value < 0) {
    throw new WeeklyTrainingReportGeneratorError(
      "INVALID_INPUT",
      `${fieldName} must be non-negative.`
    );
  }
}

function requireNonNegativeInteger(value: number, fieldName: string): void {
  requireFiniteNumber(value, fieldName);
  if (!Number.isInteger(value) || value < 0) {
    throw new WeeklyTrainingReportGeneratorError(
      "INVALID_INPUT",
      `${fieldName} must be a non-negative integer.`
    );
  }
}

function requireFiniteNumber(value: number, fieldName: string): void {
  if (!Number.isFinite(value)) {
    throw new WeeklyTrainingReportGeneratorError("INVALID_INPUT", `${fieldName} must be finite.`);
  }
}
