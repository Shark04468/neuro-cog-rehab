export function generateWeeklyTrainingReport(
  input: WeeklyTrainingReportInput
): WeeklyTrainingReport {
  validateWeeklyReportInput(input);

  const generatedAt = input.generatedAt ?? new Date().toISOString();
  const completedSessionCount = input.sessions.filter(
    (session) => session.completionStatus === "completed"
  ).length;
  const totalTrainingDurationMinutes = roundToOneDecimal(
    input.sessions.reduce((sum, session) => sum + session.durationSeconds, 0) / 60
  );
  const completionRate = calculateCompletionRate(
    input.plan.plannedSessionCount,
    completedSessionCount
  );
  const trends = buildTrendSet(input.sessions);
  const baseReport: Omit<WeeklyTrainingReport, "narrativeSummary" | "sections"> = {
    id: sanitizePlainText(
      input.reportId ??
        `weekly-report-${input.userInfo.userId}-${toDateKey(input.period.periodStart)}-${toDateKey(
          input.period.periodEnd
        )}`
    ),
    generatedAt,
    dataSensitivity: "sensitive",
    userInfo: sanitizeUserInfo(input.userInfo),
    period: sanitizePeriod(input.period),
    plannedSessionCount: input.plan.plannedSessionCount,
    sessionCount: input.sessions.length,
    completedSessionCount,
    totalTrainingDurationMinutes,
    completionRate,
    trends,
    nextWeekSuggestions: buildNextWeekSuggestions({ completionRate, trends }),
    sourceSessionIds: input.sessions.map((session) => sanitizePlainText(session.sessionId)),
    therapistNotes:
      input.therapistNotes === undefined ? null : sanitizePlainText(input.therapistNotes),
    scopeNotice: "本周报仅用于辅助训练记录、状态回顾和趋势追踪，不用于给出确定性健康结论。"
  };
  const report: WeeklyTrainingReport = {
    ...baseReport,
    narrativeSummary: buildNarrativeSummary(baseReport),
    sections: buildReportSections(baseReport)
  };

  assertNoForbiddenTerms(JSON.stringify(report));
  return report;
}

export function buildWeeklyTrainingReportView(
  report: WeeklyTrainingReport,
  audience: WeeklyTrainingReportAudience
): WeeklyTrainingReportView {
  const canViewDetailedMetrics = audience === "therapist";
  const view: WeeklyTrainingReportView = {
    audience,
    reportId: report.id,
    title:
      audience === "therapist"
        ? `${report.userInfo.displayName} 的训练周报`
        : `${report.userInfo.displayName} 的本周训练回顾`,
    generatedAt: report.generatedAt,
    summaryCards: buildSummaryCards(report, audience),
    trendCards: buildTrendCards(report, audience),
    sections: canViewDetailedMetrics ? report.sections : buildGuardianSections(report),
    nextWeekSuggestions:
      audience === "therapist"
        ? report.nextWeekSuggestions
        : report.nextWeekSuggestions.slice(0, 3).map(simplifyGuardianSuggestion),
    canViewDetailedMetrics,
    scopeNotice: report.scopeNotice
  };

  assertNoForbiddenTerms(JSON.stringify(view));
  return view;
}

export function generateWeeklyTrainingHtmlReport(
  input: WeeklyTrainingReportInput,
  options: WeeklyTrainingReportExportOptions = {}
): WeeklyTrainingHtmlExport {
  const report = generateWeeklyTrainingReport(input);
  const view = buildWeeklyTrainingReportView(report, options.audience ?? "therapist");
  const html = renderWeeklyTrainingReportHtml(view);
  assertNoForbiddenTerms(html);

  return {
    fileName: `${report.id}-${view.audience}.html`,
    mimeType: "text/html; charset=utf-8",
    html
  };
}

export function exportWeeklyTrainingReportPdf(
  input: WeeklyTrainingReportInput,
  options: WeeklyTrainingReportExportOptions = {}
): WeeklyTrainingPdfExport {
  const report = generateWeeklyTrainingReport(input);
  const view = buildWeeklyTrainingReportView(report, options.audience ?? "therapist");
  const data = buildSimplePdf(buildPdfLines(view));

  return {
    fileName: `${report.id}-${view.audience}.pdf`,
    mimeType: "application/pdf",
    data
  };
}

